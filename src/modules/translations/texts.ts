export const TRANSLATIONS_TEXTS: Record<Locale, Texts> = { de, fr, it, en };

/** Übersetzer für die Verwaltungsseite (Rückfall Deutsch, dann Schlüssel). */
export function translationsT(locale: string | null | undefined): TFunction {
  const l = normalizeLocale(locale);
  return (key, vars) => interpolate(TRANSLATIONS_TEXTS[l][key] ?? de[key] ?? key, vars);
}

/** Lesbare Meldung zu einem ungültigen Eintrag. */
export function entryErrorMessage(t: TFunction, e: EntryError): string {
  if (e.code === "placeholders") {
    const parts: string[] = [];
    if (e.missing?.length) parts.push(t("err.placeholdersMissing", { list: e.missing.map((p) => `{${p}}`).join(", ") }));
    if (e.extra?.length) parts.push(t("err.placeholdersExtra", { list: e.extra.map((p) => `{${p}}`).join(", ") }));
    return parts.join(" ");
  }
  return t(`err.${e.code}`);
}
