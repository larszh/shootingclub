/**
 * Französische Typografie: schmales geschütztes Leerzeichen (U+202F) vor ! ? ; : und innerhalb
 * der Guillemets. In ROWS stehen der Lesbarkeit halber normale Leerzeichen.
 */
export function frTypography(v: string): string {
  return v
    .replace(/ ([!?;:])/g, "\u202f$1")
    .replace(/« /g, "«\u202f")
    .replace(/ »/g, "\u202f»");
}

function build(idx: 0 | 1 | 2): Record<string, string> {
  return Object.fromEntries(Object.entries(ROWS).map(([k, row]) => [k, idx === 1 ? frTypography(row[idx]) : row[idx]]));
}

