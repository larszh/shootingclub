/** Französische Guillemets mit schmalem geschütztem Leerzeichen (U+202F). */
export function frenchSpacing(s: string): string {
  return s
    .replace(/«[ \u00A0\u202F]?/g, "«\u202F")
    .replace(/[ \u00A0\u202F]?»/g, "\u202F»")
    .replace(/ :(?=\s|$)/g, "\u00A0:")
    .replace(/ ([?!;])/g, "\u202F$1");
}

